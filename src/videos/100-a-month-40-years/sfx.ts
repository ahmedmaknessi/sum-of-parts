export const SFX_SOUNDS = ["tick", "pop", "tap", "thump", "whoosh", "swish", "chime", "riser"] as const;
export type SfxSound = (typeof SFX_SOUNDS)[number];

export type SfxEvent = {
  readonly sound: SfxSound;
  /** Absolute frame where the sound starts. */
  readonly frame: number;
  /** Linear gain (each sound file peaks at -3 dBFS). */
  readonly volume: number;
  /** Playback rate: 1 = as made, 1.12 = about two semitones higher. */
  readonly rate?: number;
};

/** The mixed track, relative to public/. Generated by `npm run sfx`. */
