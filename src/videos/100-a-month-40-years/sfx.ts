/** Gain for the whole sfx track in Video01 (one knob to balance it against the voice). */
export const SFX_TRACK_VOLUME = 1.4;

/** Default level per sound: well under the voice, so the channel stays calm. */
const LEVEL: Record<SfxSound, number> = {
  tick: 0.1,
  pop: 0.2,
  tap: 0.26,
  thump: 0.42,
  whoosh: 0.16,
  swish: 0.14,
  chime: 0.13,
  riser: 0.2,
};

/** Frames from a whoosh's start to its loudest point. */
const WHOOSH_PEAK = Math.round(0.35 * VIDEO.fps);
/** Length of the riser, so it can end exactly on a reveal. */
const RISER_FRAMES = Math.round(1.6 * VIDEO.fps);

const events: SfxEvent[] = [];

/** Adds sounds for one scene; `at` takes frames relative to the scene start. */
const scene = (id: SceneId) => {
  const start = getScene(id).startFrame;
  const T = sceneTiming(id);
  const add = (sound: SfxSound, frame: number, gain = 1, rate = 1) =>
    events.push({ sound, frame: Math.round(start + frame), volume: LEVEL[sound] * gain, rate });
  /**
   * A tick each time a counter's shown value changes, at most one every
   * `minGap` frames, with the pitch rising across the run.
   */
  const ticks = (
    valueAt: (frame: number) => number,
    from: number,
    to: number,
    { minGap = 2, gain = 1, rateFrom = 1, rateTo = 1.3 } = {},
  ) => {
    let last = valueAt(from - 1);
    let lastTick = -Infinity;
    for (let f = from; f <= to; f++) {
      const v = valueAt(f);
      if (v !== last && f - lastTick >= minGap) {
        add("tick", f, gain, rateFrom + (rateTo - rateFrom) * ((f - from) / Math.max(1, to - from)));
        lastTick = f;
      }
      last = v;
    }
  };
  return { T, add, ticks, cue: T.cue };
};

/** Soft whoosh peaking in the middle of each cross-fade. */
